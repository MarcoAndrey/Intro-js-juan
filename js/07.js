// Orden de las Operaciones

// Diviciones y multiplicaciones tiene mas peso que sumas y restas.

let resultado;

resultado = (5 + 5) * 2;

console.log(resultado);

// Incrementos

let puntaje;

puntaje = 10;

// Incremento en 1 es ++

puntaje++; // Mantiene el valor y luego da el incremento

++puntaje; // Primero incrementa y muestra el valor 12

// Decrementos --

puntaje--;

// Incrementa += segun el valor

puntaje += 10;

console.log(puntaje);
